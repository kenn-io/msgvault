// parseFrontmatter extracts name and description from the YAML
// frontmatter block we generate (simple key: value lines between
// --- fences). We parse by hand to avoid a YAML dependency.
func parseFrontmatter(t *testing.T, content string) (name, description string) {
	t.Helper()
	require.True(t, strings.HasPrefix(content, "---\n"),
		"content must start with frontmatter fence")
	rest := content[len("---\n"):]
	end := strings.Index(rest, "\n---\n")
	require.GreaterOrEqual(t, end, 0, "frontmatter must be closed with ---")
	for line := range strings.SplitSeq(rest[:end], "\n") {
		key, value, found := strings.Cut(line, ":")
		if !found {
			continue
		}
		switch strings.TrimSpace(key) {
		case "name":
			name = strings.TrimSpace(value)
		case "description":
			description = strings.TrimSpace(value)
		}
	}
	return name, description
}

func TestRender_AllSkills(t *testing.T) {
	assert := assert.New(t)
	require := require.New(t)
	rendered, err := Render("1.2.3")
	require.NoError(err)

	wantNames := []string{
		"msgvault-analytics", "msgvault-attachments", "msgvault-feedback", "msgvault-search",
	}
	var gotNames []string
	for _, sk := range rendered {
		gotNames = append(gotNames, sk.Name)
	}
	assert.Equal(wantNames, gotNames, "skills sorted by name")

	for _, sk := range rendered {
		name, description := parseFrontmatter(t, sk.Content)
		assert.Equal(sk.Name, name,
			"frontmatter name must match directory name")
		assert.NotEmpty(description)
		assert.LessOrEqual(len(description), 1024)
		assert.Contains(sk.Content, Marker,
			"rendered skill must carry the generated-by marker")
		assert.Contains(sk.Content, "v1.2.3",
			"marker line embeds the version")
		assert.NotContains(sk.Content, "{{",
			"no unrendered template actions")
		assert.NotContains(sk.Content, "\r",
			"rendered skills must use LF regardless of checkout line endings")
		// every skill embeds the shared basics section
		assert.Contains(sk.Content, "## msgvault conventions")
		assert.Contains(sk.Content, "UNTRUSTED sender-controlled data",
			"every skill must carry the untrusted-content warning")
	}
}

func TestRender_VersionDefaultsSafely(t *testing.T) {
	rendered, err := Render("dev")
	require.NoError(t, err)
	require.NotEmpty(t, rendered)
	assert.Contains(t, rendered[0].Content, "generated by msgvault vdev")
}

func TestRender_StripsLeadingVFromVersion(t *testing.T) {
	assert := assert.New(t)
	require := require.New(t)
	rendered, err := Render("v1.2.3")
	require.NoError(err)
	require.NotEmpty(rendered)
	assert.Contains(rendered[0].Content, "generated by msgvault v1.2.3",
		"a version already prefixed with v must not be double-prefixed")
	assert.NotContains(rendered[0].Content, "vv1.2.3")
}

// Exercise the consumer artifact and the actual installer, including the new
// workflow. Template parsing alone cannot catch invalid skill frontmatter.
func TestRender_InstalledArtifacts(t *testing.T) {
	assert := assert.New(t)
	require := require.New(t)
	root := filepath.Join(t.TempDir(), "agent skills [local]")
	for _, version := range []string{"dev", "v1.2.3-rc.1+build", ""} {
		rendered, err := Render(version)
		require.NoError(err)
		results, err := Install(root, rendered, false)
		require.NoError(err)
		require.Len(results, len(rendered))
		for i, sk := range rendered {
			content, err := os.ReadFile(results[i].Path)
			require.NoError(err)
			assert.Equal(sk.Content, string(content))
			parts := strings.SplitN(string(content), "---", 3)
			require.Len(parts, 3)
			var metadata struct {
				Name        string `yaml:"name"`
				Description string `yaml:"description"`
			}
			require.NoError(yaml.Unmarshal([]byte(parts[1]), &metadata))
			assert.Equal(sk.Name, metadata.Name)
			assert.NotEmpty(metadata.Description)
		}
	}
	removed, err := Uninstall(root)
	require.NoError(err)
	require.NotEmpty(removed)
	entries, err := os.ReadDir(root)
	require.NoError(err)
	assert.Empty(entries)
}
