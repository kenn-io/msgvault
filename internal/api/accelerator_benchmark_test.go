type apiQualificationManifest struct {
	Dimension    int   `json:"dimension"`
	GenerationID int64 `json:"generation_id"`
}

type apiQualificationCase struct {
	Name    string
	Ordinal int64
	Params  string
}

type apiQualificationCaseResult struct {
	Name                string  `json:"name"`
	HTTPP50MS           float64 `json:"http_p50_ms"`
	HTTPP95MS           float64 `json:"http_p95_ms"`
	QueryEmbeddingP95MS int64   `json:"query_embedding_p95_ms"`
	RetrievalP95MS      int64   `json:"retrieval_p95_ms"`
	HydrationP95MS      int64   `json:"hydration_p95_ms"`
}

type qualificationQueryEmbedder struct {
	dimension int
}

func (e qualificationQueryEmbedder) EmbedQuery(_ context.Context, text string) ([]float32, error) {
	ordinalText := strings.TrimPrefix(strings.TrimSpace(text), "ordinal")
	ordinal, err := strconv.ParseInt(ordinalText, 10, 64)
	if err != nil || ordinal <= 0 {
		return nil, fmt.Errorf("qualification query must be ordinal<N>, got %q", text)
	}
	return apiQualificationVector(ordinal, e.dimension), nil
}

// TestHTTPSQLiteAcceleratorQualification measures the complete semantic HTTP
// path, including query embedding, accelerated retrieval, bulk hydration, and
// JSON serialization. It consumes the fixture generated by the gated harness
// in internal/vector/sqlitevec/accelerator_benchmark_test.go.
func TestHTTPSQLiteAcceleratorQualification(t *testing.T) {
	dir := strings.TrimSpace(os.Getenv("MSGVAULT_ANN_QUALIFY_DIR"))
	if dir == "" {
		t.Skip("set MSGVAULT_ANN_QUALIFY_DIR to run the HTTP qualification harness")
	}
	manifestBytes, err := os.ReadFile(filepath.Join(dir, "qualification.json"))
	require.NoError(t, err)
	var manifest apiQualificationManifest
	require.NoError(t, json.Unmarshal(manifestBytes, &manifest))

	mainStore, err := store.Open(filepath.Join(dir, "msgvault.db"))
	require.NoError(t, err)
	t.Cleanup(func() { _ = mainStore.Close() })
	backend, err := sqlitevec.Open(t.Context(), sqlitevec.Options{
		Path: filepath.Join(dir, "vectors.db"), MainPath: filepath.Join(dir, "msgvault.db"),
		MainDB: mainStore.DB(), Dimension: manifest.Dimension, AcceleratorMode: "auto",
	})
	require.NoError(t, err)
	t.Cleanup(func() { _ = backend.Close() })
	status, err := backend.Accelerator(t.Context(), vector.GenerationID(manifest.GenerationID))
	require.NoError(t, err)
	require.NotNil(t, status)
	require.Equal(t, sqlitevec.AcceleratorReady, status.State)
	summaries, err := mainStore.GetMessagesSummariesByIDsContext(t.Context(), []int64{1})
	require.NoError(t, err, "qualification fixture must support production hydration")
	require.Len(t, summaries, 1, "qualification fixture must contain message 1")

	vectorConfig := vector.Config{
		Enabled: true, Backend: "sqlite-vec",
		Embeddings: vector.EmbeddingsConfig{Model: "synthetic-qualification", Dimension: manifest.Dimension},
	}
	fingerprint := vectorConfig.GenerationFingerprint()
	engine := hybrid.NewEngine(backend, mainStore.DB(), qualificationQueryEmbedder{dimension: manifest.Dimension}, hybrid.Config{
		ExpectedFingerprint: fingerprint, RRFK: 60, KPerSignal: 50,
	})
	srv := NewServerWithOptions(ServerOptions{
		Config: &config.Config{Server: config.ServerConfig{APIPort: 8080}, Vector: vectorConfig},
		Store:  mainStore, HybridEngine: engine, Backend: backend, VectorCfg: vectorConfig,
		Logger: slog.New(slog.DiscardHandler), RequestTimeout: 30 * time.Second,
	})
	iterations := int(apiQualificationEnvInt64(t, "MSGVAULT_ANN_HTTP_ITERATIONS", 20))
	cases := []apiQualificationCase{
		{Name: "unfiltered", Ordinal: 1},
		{Name: "broad_message_type", Ordinal: 1023, Params: "&message_type=email"},
		{Name: "selective_source", Ordinal: 101, Params: "&source_id=3"},
		{Name: "deleted_tombstone", Ordinal: 97},
		{Name: "multi_chunk", Ordinal: 10},
	}
	results := make([]apiQualificationCaseResult, 0, len(cases))
	for _, testCase := range cases {
		var totals []time.Duration
		var embeddingMS, retrievalMS, hydrationMS []int64
		for range iterations {
			path := "/api/v1/search?q=" + url.QueryEscape(fmt.Sprintf("ordinal%d", testCase.Ordinal)) + "&mode=vector&limit=10" + testCase.Params
			request := httptest.NewRequest(http.MethodGet, path, nil)
			response := httptest.NewRecorder()
			started := time.Now()
			srv.Router().ServeHTTP(response, request)
			totals = append(totals, time.Since(started))
			require.Equal(t, http.StatusOK, response.Code, "case %s: %s", testCase.Name, response.Body.String())
			body := response.Body.Bytes()
			var payload hybridSearchResponse
			require.NoError(t, json.Unmarshal(body, &payload))
			require.NotEmpty(t, payload.Results, "case %s: %s", testCase.Name, body)
			embeddingMS = append(embeddingMS, payload.Timings.QueryEmbeddingMS)
			retrievalMS = append(retrievalMS, payload.Timings.RetrievalMS)
			hydrationMS = append(hydrationMS, payload.Timings.HydrationMS)
		}
		results = append(results, apiQualificationCaseResult{
			Name: testCase.Name, HTTPP50MS: apiPercentileDurationMS(totals, 0.50),
			HTTPP95MS:           apiPercentileDurationMS(totals, 0.95),
			QueryEmbeddingP95MS: apiPercentileInt64(embeddingMS, 0.95),
			RetrievalP95MS:      apiPercentileInt64(retrievalMS, 0.95),
			HydrationP95MS:      apiPercentileInt64(hydrationMS, 0.95),
		})
	}
	var similarTotals []time.Duration
	for range iterations {
		request := httptest.NewRequest(http.MethodGet, "/api/v1/search/similar?message_id=1&limit=10", nil)
		response := httptest.NewRecorder()
		started := time.Now()
		srv.Router().ServeHTTP(response, request)
		similarTotals = append(similarTotals, time.Since(started))
		require.Equal(t, http.StatusOK, response.Code, "find similar: %s", response.Body.String())
		var payload similarSearchResponse
		require.NoError(t, json.Unmarshal(response.Body.Bytes(), &payload))
		require.NotEmpty(t, payload.Messages)
		for _, message := range payload.Messages {
			require.NotEqual(t, int64(1), message.ID, "find similar must exclude its seed")
		}
	}
	results = append(results, apiQualificationCaseResult{
		Name: "find_similar", HTTPP50MS: apiPercentileDurationMS(similarTotals, 0.50),
		HTTPP95MS: apiPercentileDurationMS(similarTotals, 0.95),
	})
	encoded, err := json.Marshal(results)
	require.NoError(t, err)
	t.Logf("HTTP_QUALIFICATION_REPORT=%s", encoded)
	for _, result := range results {
		require.LessOrEqual(t, result.HTTPP95MS, float64(2000), "case %s warm HTTP p95", result.Name)
	}
}

func apiQualificationVector(ordinal int64, dimension int) []float32 {
	clusterState := uint64(ordinal/64) + 0x9e3779b97f4a7c15
	pointState := uint64(ordinal) + 0xd1b54a32d192ed03
	result := make([]float32, dimension)
	var norm float64
	for i := range result {
		clusterState = apiQualificationXorshift(clusterState)
		pointState = apiQualificationXorshift(pointState)
		base := float64(int32(clusterState>>32)) / float64(math.MaxInt32)
		jitter := float64(int32(pointState>>32)) / float64(math.MaxInt32)
		value := base + 0.025*jitter
		result[i] = float32(value)
		norm += value * value
	}
	scale := float32(1 / math.Sqrt(norm))
	for i := range result {
		result[i] *= scale
	}
	return result
}

func apiQualificationXorshift(value uint64) uint64 {
	value ^= value << 13
	value ^= value >> 7
	value ^= value << 17
	return value
}

func apiQualificationEnvInt64(t *testing.T, name string, defaultValue int64) int64 {
	t.Helper()
	value := strings.TrimSpace(os.Getenv(name))
	if value == "" {
		return defaultValue
	}
	parsed, err := strconv.ParseInt(value, 10, 64)
	require.NoErrorf(t, err, "parse %s", name)
	require.Positivef(t, parsed, "%s", name)
	return parsed
}

func apiPercentileDurationMS(values []time.Duration, percentile float64) float64 {
	ordered := append([]time.Duration(nil), values...)
	slices.Sort(ordered)
	index := min(max(int(math.Ceil(percentile*float64(len(ordered))))-1, 0), len(ordered)-1)
	return float64(ordered[index]) / float64(time.Millisecond)
}

func apiPercentileInt64(values []int64, percentile float64) int64 {
	ordered := append([]int64(nil), values...)
	slices.Sort(ordered)
	index := min(max(int(math.Ceil(percentile*float64(len(ordered))))-1, 0), len(ordered)-1)
	return ordered[index]
}
