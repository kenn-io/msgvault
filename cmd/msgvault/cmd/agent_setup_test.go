func TestAgentSetup(t *testing.T) {
	home := t.TempDir()
	setTestHome(t, home)
	t.Setenv("CODEX_HOME", filepath.Join(home, ".codex"))
	t.Setenv("CLAUDE_CONFIG_DIR", filepath.Join(home, ".claude"))
	t.Setenv("PATH", t.TempDir())
	opts := agentsetup.Options{Agents: []string{"claude", "codex"}, SetupCommand: "msgvault agent setup", Items: agentSetupItems}
	report, err := agentsetup.Run(t.Context(), opts)
	require.NoError(t, err)
	require.Len(t, report.Rows, 4)
	assert.Equal(t, "skills", report.Rows[0].Piece)
	assert.Equal(t, "mcp msgvault", report.Rows[1].Piece)
	assert.Equal(t, "skills", report.Rows[2].Piece)
	assert.Equal(t, "mcp msgvault", report.Rows[3].Piece)
	require.FileExists(t, filepath.Join(home, ".claude", "skills", "msgvault-search", "SKILL.md"))
	require.FileExists(t, filepath.Join(home, ".codex", "skills", "msgvault-search", "SKILL.md"))
	paths := []string{filepath.Join(home, ".claude", "skills", "msgvault-search", "SKILL.md"), filepath.Join(home, ".codex", "skills", "msgvault-search", "SKILL.md")}
	old := time.Unix(1600000000, 0)
	for _, path := range paths {
		require.NoError(t, os.Chtimes(path, old, old))
	}
	_, err = agentsetup.Run(t.Context(), opts)
	require.NoError(t, err)
	for _, path := range paths {
		info, err := os.Stat(path)
		require.NoError(t, err)
		assert.Equal(t, old, info.ModTime())
	}
	opts.Agents = []string{"gemini"}
	report, err = agentsetup.Run(t.Context(), opts)
	require.NoError(t, err)
	require.Len(t, report.Rows, 1)
	assert.Equal(t, agentsetup.StateUnknown, report.Rows[0].State)
}

func TestAgentSetupCustomRootsAndScopedRepair(t *testing.T) {
	home := t.TempDir()
	claude := t.TempDir()
	codex := t.TempDir()
	setTestHome(t, home)
	t.Setenv("CLAUDE_CONFIG_DIR", claude)
	t.Setenv("CODEX_HOME", codex)
	t.Setenv("PATH", t.TempDir())
	opts := agentsetup.Options{Agents: []string{"claude", "codex"}, SetupCommand: "msgvault agent setup", Items: agentSetupItems}
	report, err := agentsetup.Run(t.Context(), opts)
	require.NoError(t, err)
	assert.Equal(t, agentsetup.StateOK, report.Rows[0].State)
	assert.Equal(t, agentsetup.StateOK, report.Rows[2].State)
	claudeSkill := filepath.Join(claude, "skills", "msgvault-search", "SKILL.md")
	codexSkill := filepath.Join(codex, "skills", "msgvault-search", "SKILL.md")
	require.FileExists(t, claudeSkill)
	require.FileExists(t, codexSkill)
	require.NoError(t, os.WriteFile(claudeSkill, []byte("claude custom"), 0o600))
	require.NoError(t, os.WriteFile(codexSkill, []byte("codex custom"), 0o600))
	report, err = agentsetup.Run(t.Context(), opts)
	require.NoError(t, err)
	assert.Equal(t, agentsetup.StateModified, report.Rows[0].State)
	assert.Equal(t, "msgvault skills install --force --agent claude", report.Rows[0].NextStep)
	var output bytes.Buffer
	require.NoError(t, runSkillsInstall(&output, []string{"claude"}, "", true))
	content, err := os.ReadFile(codexSkill)
	require.NoError(t, err)
	assert.Equal(t, "codex custom", string(content))
	content, err = os.ReadFile(claudeSkill)
	require.NoError(t, err)
	assert.Contains(t, string(content), "generated by msgvault")
}

func TestAgentSetupSelectsInstalledAgents(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("shell stub requires Unix")
	}
	home := t.TempDir()
	setTestHome(t, home)
	t.Setenv("CLAUDE_CONFIG_DIR", filepath.Join(home, ".claude"))
	t.Setenv("CODEX_HOME", filepath.Join(home, ".codex"))
	bin := t.TempDir()
	t.Setenv("PATH", bin)
	require.NoError(t, os.WriteFile(filepath.Join(bin, "claude"), []byte("#!/bin/sh\nexit 1\n"), 0o755))
	status, err := checkAgentSetup(t.Context())
	require.NoError(t, err)
	require.Len(t, status.Rows, 2)
	assert.NoDirExists(t, filepath.Join(home, ".claude"))
	assert.NoDirExists(t, filepath.Join(home, ".codex"))
	setup, err := agentsetup.Run(t.Context(), agentsetup.Options{SetupCommand: "msgvault agent setup", Items: agentSetupItems})
	require.NoError(t, err)
	require.Len(t, setup.Rows, len(status.Rows))
	for i := range setup.Rows {
		assert.Equal(t, setup.Rows[i].Agent, status.Rows[i].Agent)
		assert.Equal(t, setup.Rows[i].Piece, status.Rows[i].Piece)
	}
}

func TestAgentSetupArchiveSelection(t *testing.T) {
	t.Setenv("MSGVAULT_HOME", "")
	flags := rootCmd.PersistentFlags()
	oldHome, _ := flags.GetString("home")
	oldConfig, _ := flags.GetString("config")
	t.Cleanup(func() { _ = flags.Set("home", oldHome); _ = flags.Set("config", oldConfig) })
	check := func(want ...string) string {
		t.Helper()
		items, err := agentSetupItems("claude")
		require.NoError(t, err)
		commands, err := items[1].Commands()
		require.NoError(t, err)
		for _, part := range want {
			assert.Contains(t, commands.POSIX, part)
		}
		return commands.POSIX
	}
	cmd := check("msgvault", "mcp")
	assert.NotContains(t, cmd, "--home")
	assert.NotContains(t, cmd, "--env")
	home := filepath.Join(t.TempDir(), "archive")
	require.NoError(t, flags.Set("home", home))
	check("--home", home, "mcp")
	require.NoError(t, flags.Set("home", ""))
	t.Setenv("MSGVAULT_HOME", home)
	cmd = check("--home", home, "mcp")
	assert.NotContains(t, cmd, "--env")
	require.NoError(t, flags.Set("config", "relative-config"))
	absConfig, err := filepath.Abs("relative-config")
	require.NoError(t, err)
	cmd = check("--config", absConfig)
	assert.NotContains(t, cmd, "--home")
	assert.NotContains(t, cmd, "--env")
	t.Setenv("MSGVAULT_HOME", "")
	require.NoError(t, flags.Set("home", "relative-archive"))
	require.NoError(t, flags.Set("config", "relative-config"))
	absHome, err := filepath.Abs("relative-archive")
	require.NoError(t, err)
	check("--home", absHome, "--config", absConfig)
	require.NoError(t, flags.Set("home", "~/archive"))
	check("~/archive")
}

func TestReviewSetupPreservesCodexSettingsWithHome(t *testing.T) {
	home := t.TempDir()
	setTestHome(t, home)
	codex := filepath.Join(home, "codex")
	require.NoError(t, os.MkdirAll(codex, 0o700))
	t.Setenv("CODEX_HOME", codex)
	t.Setenv("MSGVAULT_HOME", filepath.Join(home, "archive"))
	t.Setenv("PATH", t.TempDir())
	path := filepath.Join(codex, "config.toml")
	require.NoError(t, os.WriteFile(path, []byte("[mcp_servers.msgvault]\ncommand = 'old'\nargs = ['mcp']\nenabled = false\nstartup_timeout_sec = 37\n[mcp_servers.msgvault.env]\nCUSTOM = 'keep'\n"), 0o600))
	_, err := agentsetup.Run(t.Context(), agentsetup.Options{Agents: []string{"codex"}, SetupCommand: "msgvault agent setup", Items: agentSetupItems})
	require.NoError(t, err)
	content, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Contains(t, string(content), "enabled = false")
	assert.Contains(t, string(content), "startup_timeout_sec = 37")
	assert.Contains(t, string(content), "CUSTOM = ")
	assert.Contains(t, string(content), "keep")
}
