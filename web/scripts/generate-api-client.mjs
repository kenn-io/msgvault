import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, resolve } from 'node:path';
import { generate } from 'orval';

const webDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(webDirectory, '..');
const generatedDirectory = join(webDirectory, 'src/lib/api/generated');

function generatedSources(directory, base = directory, sources = new Map()) {
  if (!existsSync(directory)) return sources;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const filePath = join(directory, entry.name);
    if (entry.isDirectory()) {
      generatedSources(filePath, base, sources);
    } else if (entry.name.endsWith('.ts')) {
      sources.set(relative(base, filePath), readFileSync(filePath, 'utf8'));
    }
  }
  return sources;
}

function writeIndex() {
  const exports = ["export * from './models';"];
  for (const entry of readdirSync(generatedDirectory, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === 'models') continue;
    const serviceName = `${entry.name
      .split('-')
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join('')}Service`;
    exports.push(`export * as ${serviceName} from './${entry.name}/${entry.name}';`);
  }
  writeFileSync(join(generatedDirectory, 'index.ts'), `${exports.sort().join('\n')}\n`);
}

function wrapClientResponses() {
  for (const entry of readdirSync(generatedDirectory, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === 'models') continue;
    const filePath = join(generatedDirectory, entry.name, `${entry.name}.ts`);
    const source = readFileSync(filePath, 'utf8')
      .replace(
        /import \{ orvalFetch \} from ["']\.\.\/\.\.\/runtime["'];/,
        'import { orvalFetch, type APIResponse } from "../../runtime";'
      )
      .replace(/: Promise<([^\n]+)> =>/g, ': Promise<APIResponse<$1>> =>');
    writeFileSync(filePath, source);
  }
}

const verifyGenerated = process.argv.includes('--check');
const previousGeneratedSources = verifyGenerated ? generatedSources(generatedDirectory) : undefined;
const temporaryDirectory = mkdtempSync(join(tmpdir(), 'msgvault-openapi-'));

try {
  const specPath = join(temporaryDirectory, 'openapi.yaml');
  writeFileSync(specPath, readFileSync(join(repositoryRoot, 'api/openapi.yaml')));

  rmSync(generatedDirectory, { recursive: true, force: true });
  await generate(
    {
      input: specPath,
      output: {
        client: 'fetch',
        mode: 'tags-split',
        target: generatedDirectory,
        schemas: join(generatedDirectory, 'models'),
        clean: true,
        formatter: 'prettier',
        urlEncodeParameters: true,
        override: {
          fetch: { includeHttpResponseReturnType: false },
          header: () => ['Generated by Orval. Do not edit manually.'],
          mutator: {
            path: join(webDirectory, 'src/lib/api/runtime.ts'),
            name: 'orvalFetch'
          },
          useNamedParameters: true
        }
      }
    },
    webDirectory
  );
  wrapClientResponses();
  writeIndex();
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}

if (previousGeneratedSources) {
  const currentGeneratedSources = generatedSources(generatedDirectory);
  const paths = new Set([...previousGeneratedSources.keys(), ...currentGeneratedSources.keys()]);
  const changed = [...paths].filter(
    (filePath) => previousGeneratedSources.get(filePath) !== currentGeneratedSources.get(filePath)
  );
  if (changed.length > 0) {
    throw new Error(`generated API client was stale and has been regenerated:\n${changed.join('\n')}`);
  }
}
